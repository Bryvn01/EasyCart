const fs = require('fs');
const path = require('path');

function ensureEslintPluginReactRulesIndex() {
  const pkgRoot = path.join(__dirname, '..', 'node_modules', 'eslint-plugin-react');
  const rulesDir = path.join(pkgRoot, 'lib', 'rules');
  const rulesIndex = path.join(rulesDir, 'index.js');

  if (!fs.existsSync(pkgRoot) || !fs.existsSync(rulesDir)) {
    return;
  }

  if (fs.existsSync(rulesIndex)) {
    return;
  }

  const contents = `'use strict';\n\nconst fs = require('fs');\nconst path = require('path');\n\n// Auto-generated by scripts/patch-eslint-plugin-react.js\n// Some installs are missing this entrypoint; eslint-plugin-react expects it.\n\nconst entries = fs\n  .readdirSync(__dirname)\n  .filter((f) => f.endsWith('.js') && f !== 'index.js')\n  .map((f) => [path.basename(f, '.js'), require('./' + f)]);\n\nmodule.exports = Object.fromEntries(entries);\n`;

  fs.writeFileSync(rulesIndex, contents, 'utf8');
}

try {
  ensureEslintPluginReactRulesIndex();
} catch (err) {
  // Don't fail installs/builds because of a patching step.
  // eslint will surface issues if it still can't load.
}
